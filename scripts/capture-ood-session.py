#!/usr/bin/env python3
"""Capture an Open OnDemand (OOD) browser session for Geoweaver Agent API (Path B).

Opens the Connect / Geoweaver URL so you can finish campus login (e.g. GMU
Shibboleth). Writes a Netscape cookie jar and an env file under
``~/.config/geoweaver-agent/`` (mode 0600). Cursor reads those paths — do not
paste cookies into chat.

Usage:
  python3 scripts/capture-ood-session.py \\
    'https://ondemand.example.edu/rnode/HOST/PORT/Geoweaver/web/geoweaver'

Preferred engine: Playwright Chromium (headed).
  pip install playwright && playwright install chromium

Fallback: open the system browser, wait for Enter, then try browser_cookie3
  pip install browser-cookie3

After capture, mint a Geoweaver Bearer against the same GEOWEAVER_BASE_URL
(see docs/agent-api.md). Cookies alone are not enough for /api/v1.
"""

from __future__ import annotations

import argparse
import os
import shlex
import stat
import sys
import threading
import time
import webbrowser
from datetime import datetime, timezone
from http.cookiejar import MozillaCookieJar
from pathlib import Path
from typing import Iterable, List, Optional, Tuple
from urllib.parse import urlparse, urlunparse

CONFIG_DIR_NAME = "geoweaver-agent"
COOKIE_JAR_NAME = "ood-cookies.txt"
ENV_FILE_NAME = "ood-env.sh"
META_FILE_NAME = "ood-session.meta"
README_NAME = "README.txt"

IDP_HOST_HINTS = (
    "shibboleth",
    "idp.",
    "login.",
    "sso.",
    "cas.",
)


def config_dir() -> Path:
    xdg = os.environ.get("XDG_CONFIG_HOME")
    if xdg:
        return Path(xdg) / CONFIG_DIR_NAME
    return Path.home() / ".config" / CONFIG_DIR_NAME


def chmod_private(path: Path) -> None:
    try:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass


def normalize_base_url(raw: str) -> str:
    """Strip /web/... (and trailing slash) so Agent API lives under .../Geoweaver."""
    raw = raw.strip()
    if not raw:
        raise SystemExit("URL is empty")
    parsed = urlparse(raw)
    if not parsed.scheme or not parsed.netloc:
        raise SystemExit(f"Not an absolute URL: {raw}")
    path = parsed.path or ""
    marker = "/Geoweaver"
    idx = path.find(marker)
    if idx < 0:
        raise SystemExit(
            "URL must contain '/Geoweaver' (Connect UI or base). "
            f"Got path={path!r}"
        )
    base_path = path[: idx + len(marker)]
    return urlunparse((parsed.scheme, parsed.netloc, base_path, "", "", "")).rstrip(
        "/"
    )


def looks_logged_in(url: str, base: str) -> bool:
    """True when the browser has left campus IdP and is on the OOD/Geoweaver host."""
    u = (url or "").lower()
    if not u or u.startswith("about:") or u.startswith("chrome"):
        return False
    if any(h in u for h in IDP_HOST_HINTS):
        return False
    host = urlparse(base).netloc.lower()
    if host not in u:
        return False
    # Geoweaver UI, or OOD reverse-proxy path still on the same portal host
    return (
        "/geoweaver" in u
        or "/rnode/" in u
        or "/node/" in u
        or "/pun/" in u
    )


def _wait_for_enter(done: threading.Event) -> None:
    """Background: any Enter in this terminal finishes capture immediately."""
    try:
        input()
    except EOFError:
        pass
    done.set()


def write_netscape_jar(path: Path, cookies: Iterable[dict]) -> int:
    """Write Netscape cookie file. Each cookie dict: name, value, domain, path, expires, secure."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by Geoweaver scripts/capture-ood-session.py",
        "# Do not commit. Mode should be 0600.",
        "",
    ]
    count = 0
    for c in cookies:
        name = c.get("name")
        value = c.get("value")
        if not name or value is None:
            continue
        domain = c.get("domain") or ""
        if not domain:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        cpath = c.get("path") or "/"
        expires = c.get("expires")
        if expires is None:
            # Session cookie: far-future so curl still sends it this session
            expires = int(time.time()) + 7 * 24 * 3600
        else:
            try:
                expires = int(expires)
            except (TypeError, ValueError):
                expires = int(time.time()) + 7 * 24 * 3600
        secure = "TRUE" if c.get("secure") else "FALSE"
        # domain FLAG path secure expiration name value
        lines.append(
            f"{domain}\t{include_sub}\t{cpath}\t{secure}\t{expires}\t{name}\t{value}"
        )
        count += 1
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    chmod_private(path)
    return count


def write_env_and_meta(base: str, jar: Path, source: str) -> Tuple[Path, Path]:
    d = config_dir()
    d.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(d, stat.S_IRWXU)
    except OSError:
        pass

    env_path = d / ENV_FILE_NAME
    env_body = f"""# Geoweaver OOD session env — generated {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}
# Re-run scripts/capture-ood-session.py after each new OOD job (PORT changes).
# Do not commit. Do not paste cookie file contents into chat.
export GEOWEAVER_BASE_URL={shlex.quote(base)}
export GEOWEAVER_OOD_COOKIE_JAR={shlex.quote(str(jar))}
# Bearer is separate — mint with POST $GEOWEAVER_BASE_URL/api/v1/tokens (GUI password).
# export GEOWEAVER_API_TOKEN=…   # from secret store only
"""
    env_path.write_text(env_body, encoding="utf-8")
    chmod_private(env_path)

    meta_path = d / META_FILE_NAME
    meta_path.write_text(
        "\n".join(
            [
                f"captured_at_utc={datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
                f"geoweaver_base_url={base}",
                f"cookie_jar={jar}",
                f"capture_source={source}",
                "note=Re-capture when OOD session expires or PORT changes.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    chmod_private(meta_path)

    readme = d / README_NAME
    readme.write_text(
        "\n".join(
            [
                "Geoweaver agent OOD session directory",
                "",
                "Files:",
                f"  {COOKIE_JAR_NAME}  — Netscape cookie jar (secret, 0600)",
                f"  {ENV_FILE_NAME}       — GEOWEAVER_BASE_URL + GEOWEAVER_OOD_COOKIE_JAR",
                "",
                "Load for this shell:",
                f"  source {env_path}",
                "",
                "Smoke (cookies only — may still need Bearer for non-health routes):",
                '  curl -sS -b "$GEOWEAVER_OOD_COOKIE_JAR" "$GEOWEAVER_BASE_URL/api/v1/health"',
                "",
                "Never paste cookie contents into Cursor chat. Point the agent at these paths.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return env_path, meta_path


def capture_playwright(start_url: str, base: str, timeout_s: int) -> List[dict]:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError as e:
        raise RuntimeError(
            "Playwright not installed. Run: pip install playwright && playwright install chromium"
        ) from e

    print("Opening headed Chromium. Complete campus login in THAT window.", flush=True)
    print(f"Start URL: {start_url}", flush=True)
    print("", flush=True)
    print(">>> When login is done (Geoweaver UI visible), press Enter HERE to save cookies.", flush=True)
    print("    (Auto-detect also runs; Enter always works and does not wait for timeout.)", flush=True)
    print("", flush=True)

    enter_done = threading.Event()
    enter_thread = threading.Thread(target=_wait_for_enter, args=(enter_done,), daemon=True)
    enter_thread.start()

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        context = browser.new_context()
        page = context.new_page()
        page.goto(start_url, wait_until="domcontentloaded")
        deadline = time.time() + timeout_s
        last_status = 0.0
        reason = "timeout"
        while time.time() < deadline:
            if enter_done.is_set():
                reason = "enter"
                print("Enter pressed — saving cookies now…", flush=True)
                break
            try:
                current = page.url
            except Exception:
                current = ""
            if looks_logged_in(current, base):
                # Prefer a clear Geoweaver path; otherwise wait for Enter unless /geoweaver seen
                if "/geoweaver" in current.lower():
                    reason = "auto-detect"
                    print(f"Detected Geoweaver session — saving cookies…", flush=True)
                    break
            now = time.time()
            if now - last_status >= 15:
                print(f"…still waiting (press Enter when done). page={current[:120]}", flush=True)
                last_status = now
            time.sleep(0.5)
        else:
            if not enter_done.is_set():
                print("Timed out waiting — saving whatever cookies exist now…", flush=True)
                reason = "timeout"

        # Small settle so post-login Set-Cookie can land
        time.sleep(1.0)
        cookies = context.cookies()
        browser.close()

    print(f"Capture trigger: {reason}", flush=True)

    # Playwright cookie shape → our dict
    out = []
    for c in cookies:
        out.append(
            {
                "name": c.get("name"),
                "value": c.get("value"),
                "domain": c.get("domain"),
                "path": c.get("path") or "/",
                "expires": c.get("expires") if c.get("expires", -1) > 0 else None,
                "secure": bool(c.get("secure")),
            }
        )
    return out


def capture_system_browser(start_url: str, base: str) -> List[dict]:
    print("Opening system default browser…", flush=True)
    webbrowser.open(start_url)
    print(
        "Complete campus login in the browser, open Geoweaver until the UI loads,",
        flush=True,
    )
    print("then press Enter here to read cookies from the browser profile…", flush=True)
    try:
        input()
    except EOFError:
        pass

    try:
        import browser_cookie3
    except ImportError as e:
        raise RuntimeError(
            "browser_cookie3 not installed. Run: pip install browser-cookie3\n"
            "Or install Playwright for the preferred flow:\n"
            "  pip install playwright && playwright install chromium"
        ) from e

    host = urlparse(base).hostname or ""
    jar = MozillaCookieJar()
    loaders = []
    for name, loader in (
        ("chrome", getattr(browser_cookie3, "chrome", None)),
        ("chromium", getattr(browser_cookie3, "chromium", None)),
        ("firefox", getattr(browser_cookie3, "firefox", None)),
        ("safari", getattr(browser_cookie3, "safari", None)),
    ):
        if loader is None:
            continue
        loaders.append((name, loader))

    errors = []
    for name, loader in loaders:
        try:
            cj = loader(domain_name=host)
            for c in cj:
                jar.set_cookie(c)
            print(f"Loaded cookies via {name}", flush=True)
        except Exception as ex:
            errors.append(f"{name}: {ex}")

    cookies = []
    for c in jar:
        cookies.append(
            {
                "name": c.name,
                "value": c.value,
                "domain": c.domain if c.domain.startswith(".") else c.domain,
                "path": c.path or "/",
                "expires": c.expires,
                "secure": bool(c.secure),
            }
        )

    if not cookies:
        detail = "; ".join(errors) if errors else "no cookies for host"
        raise RuntimeError(
            f"No cookies found for host {host!r}. {detail}\n"
            "Prefer: pip install playwright && playwright install chromium"
        )
    return cookies


def smoke_hint(base: str, jar: Path) -> None:
    print("", flush=True)
    print("Next (do not paste cookie contents into chat):", flush=True)
    print(f"  source {config_dir() / ENV_FILE_NAME}", flush=True)
    print(
        f'  curl -sS -b "{jar}" "{base}/api/v1/health"',
        flush=True,
    )
    print(
        "  # expect {\"status\":\"up\"} — if still IdP HTML, re-run capture after login",
        flush=True,
    )
    print(
        "  # then mint Bearer against the same GEOWEAVER_BASE_URL (GUI localhost password)",
        flush=True,
    )


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Capture OOD session cookies for Geoweaver Agent API (local file only)."
    )
    parser.add_argument(
        "url",
        help="Connect UI or Geoweaver base URL containing /Geoweaver",
    )
    parser.add_argument(
        "--engine",
        choices=("auto", "playwright", "system"),
        default="auto",
        help="Capture engine (default: auto = playwright then system)",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=600,
        help="Seconds to wait for Playwright auto-detect (default 600)",
    )
    args = parser.parse_args(argv)

    base = normalize_base_url(args.url)
    # Prefer opening the UI path so the human sees Geoweaver after login
    start_url = args.url.strip()
    if start_url.rstrip("/").endswith("/Geoweaver"):
        start_url = base + "/web/geoweaver"

    jar_path = config_dir() / COOKIE_JAR_NAME
    print(f"GEOWEAVER_BASE_URL={base}", flush=True)
    print(f"Cookie jar will be: {jar_path}", flush=True)

    cookies: List[dict] = []
    source = ""
    engines: List[str]
    if args.engine == "auto":
        engines = ["playwright", "system"]
    else:
        engines = [args.engine]

    last_err: Optional[BaseException] = None
    for eng in engines:
        try:
            if eng == "playwright":
                cookies = capture_playwright(start_url, base, args.timeout)
                source = "playwright"
            else:
                cookies = capture_system_browser(start_url, base)
                source = "system-browser+browser_cookie3"
            break
        except Exception as e:
            last_err = e
            print(f"Engine {eng} failed: {e}", flush=True)

    if not cookies:
        print(f"Capture failed: {last_err}", file=sys.stderr)
        return 1

    n = write_netscape_jar(jar_path, cookies)
    if n == 0:
        print("No cookies written (empty set).", file=sys.stderr)
        return 1

    env_path, _meta = write_env_and_meta(base, jar_path, source)
    print(f"Wrote {n} cookies to {jar_path} (mode 0600)", flush=True)
    print(f"Wrote {env_path}", flush=True)
    print(f"Capture source: {source}", flush=True)
    # Never print cookie names/values
    smoke_hint(base, jar_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
